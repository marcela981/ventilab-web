/*
* Funcionalidad: E2E (1) quiz with immediate feedback, published grade and AI feedback (Bloque 3)
* Descripción: A brand-new student of a new group opens a QUIZ of two single-choice questions, gets the immediate feedback of each answer when choosing it ("¡Correcto! 🎉" and `Casi. La respuesta correcta era "…"`, checked by the server through POST …/check), sends it ("Enviar quiz") and lands on the result, whose grade is already published (QUIZ auto-publication: "1 de 2 correctas" in the result band). The general AI feedback is generated by the real backend against the fake LLM (scripts/e2e/fake-llm.mjs, OPENAI_BASE_URL) and shown without the "Retroalimentación automática" label; rating it "Sí, fue útil" sends PUT /api/ai-ratings with targetType GRADE_FEEDBACK and surface EVALUATION_FEEDBACK. Depends on @playwright/test and the learning and evaluations e2e helpers.
* Versión: 0.1
* Autor: Marcela Mazo Castro
* Proyecto: VentyLab
* Tesis: Desarrollo de una aplicación web para la enseñanza de mecánica ventilatoria que integre un sistema de retroalimentación usando modelos de lenguaje
* Institución: Universidad del Valle
* Contacto: marcela.mazo@correounivalle.edu.co
*/

import { expect, test } from "@playwright/test";
import { freshGroup, retireEvaluation, runTag, type SeededEvaluation, seedEvaluation, signInTeacher } from "../support/evaluations";
import { contextFor } from "../support/learning";

test("(1) quiz: immediate feedback, grade published on submit, AI feedback and its rating", async ({ browser, request, baseURL }) => {
  test.setTimeout(180_000);
  const teacher = await signInTeacher(request);
  const { groupId, students: [student] } = await freshGroup(request, teacher.api, "quiz");
  let evaluation: SeededEvaluation | null = null;

  try {
    evaluation = await seedEvaluation(teacher.api, {
      type: "QUIZ",
      title: `E2E quiz ${runTag()}`,
      questions: [
        { type: "SINGLE_CHOICE", prompt: "¿Qué parámetro se programa en VCV?", options: [{ content: "Volumen corriente", isCorrect: true }, { content: "Presión inspiratoria" }], explanation: "En VCV se fija el volumen." },
        { type: "SINGLE_CHOICE", prompt: "¿Qué valor de PEEP es fisiológico?", options: [{ content: "5 cmH2O", isCorrect: true }, { content: "20 cmH2O" }] },
      ],
    }, groupId);

    const context = await contextFor(browser, baseURL ?? "http://localhost:3000", student!);
    const page = await context.newPage();

    await page.goto(`/evaluations/${evaluation.id}`);
    await expect(page.getByRole("heading", { level: 1, name: evaluation.title })).toBeVisible({ timeout: 30_000 });
    await page.getByRole("button", { name: "Comenzar" }).click();
    await expect(page).toHaveURL(/\/attempts\/[^/]+$/, { timeout: 30_000 });

    // Immediate feedback: the server checks each single-choice answer when it is chosen.
    const firstCheck = page.waitForResponse((res) => res.request().method() === "POST" && /\/answers\/[^/]+\/check$/.test(res.url()));

    await page.getByRole("radio", { name: "Volumen corriente" }).check();
    expect((await firstCheck).ok()).toBe(true);
    await expect(page.getByText("¡Correcto! 🎉")).toBeVisible();
    await expect(page.getByText("En VCV se fija el volumen.")).toBeVisible();

    await page.getByRole("radio", { name: "20 cmH2O" }).check();
    await expect(page.getByText("Casi. La respuesta correcta era \"5 cmH2O\"")).toBeVisible({ timeout: 15_000 });
    // A revealed answer is locked.
    await expect(page.getByRole("radio", { name: "5 cmH2O" })).toBeDisabled();

    await page.getByRole("button", { name: "Enviar quiz" }).click();
    await page.getByRole("dialog", { name: "¿Enviar el intento?" }).getByRole("button", { name: "Enviar", exact: true }).click();
    await expect(page).toHaveURL(/\/result$/, { timeout: 30_000 });

    // QUIZ grades are published on submit.
    await expect(page.getByText("1 de 2 correctas")).toBeVisible({ timeout: 30_000 });
    await expect(page.getByText(/^(¡Aprobado! 🎉|Reprobado 😔)$/)).toBeVisible();

    // General AI feedback from the fake LLM (not the deterministic fallback).
    const overall = page.getByRole("region", { name: "Retroalimentación general" });

    await expect(overall).toContainText("proveedor falso de E2E", { timeout: 60_000 });
    await expect(overall).not.toContainText("Retroalimentación automática");

    const rating = page.waitForRequest((req) => req.method() === "PUT" && req.url().endsWith("/api/ai-ratings"));
    const ratingResponse = page.waitForResponse((res) => res.request().method() === "PUT" && res.url().endsWith("/api/ai-ratings"));

    await expect(overall.getByText("¿Te fue útil?")).toBeVisible();
    await overall.getByRole("button", { name: "Sí, fue útil" }).click();
    expect((await rating).postDataJSON()).toMatchObject({ targetType: "GRADE_FEEDBACK", helpful: true, surface: "EVALUATION_FEEDBACK" });
    expect((await ratingResponse).ok()).toBe(true);
    await expect(overall.getByRole("button", { name: "Sí, fue útil" })).toHaveAttribute("aria-pressed", "true");

    // The rating survives a reload (embedded myRating).
    await page.reload();
    await expect(page.getByRole("region", { name: "Retroalimentación general" }).getByRole("button", { name: "Sí, fue útil" })).toHaveAttribute("aria-pressed", "true", { timeout: 30_000 });
    await context.close();
  } finally {
    await retireEvaluation(teacher.api, evaluation);
  }
});
