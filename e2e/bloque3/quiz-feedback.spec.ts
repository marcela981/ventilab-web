/*
* Funcionalidad: E2E (1) quiz autosaved, held until the teacher release, then the grade and the AI feedback (Bloque 3, ajustes C1)
* Descripción: A brand-new student of a new group opens a QUIZ of two single-choice questions, gets the immediate feedback of each answer when choosing it ("¡Correcto! 🎉" and `Casi. La respuesta correcta era "…"`, checked by the server through POST …/check), sends it ("Enviar quiz") and lands on the result, whose grade is already published (QUIZ auto-publication: "1 de 2 correctas" in the result band). The general AI feedback is generated by the real backend against the fake LLM (scripts/e2e/fake-llm.mjs, OPENAI_BASE_URL) and shown without the "Retroalimentación automática" label; rating it "Sí, fue útil" sends PUT /api/ai-ratings with targetType GRADE_FEEDBACK and surface EVALUATION_FEEDBACK. Depends on @playwright/test and the learning and evaluations e2e helpers. v0.2 (ajustes C1): no immediate feedback and no auto-publication: each answer is autosaved (PUT, no verdict, no check), after "Enviar quiz" the result says "Entregado — en espera de resultados" without any count, and only after the teacher releases the grade and the answers (POST …/publish with scope GRADE_AND_ANSWERS) does the student see "1 de 2 correctas" and the AI feedback.
* Versión: 0.2
* Autor: Marcela Mazo Castro
* Proyecto: VentyLab
* Tesis: Desarrollo de una aplicación web para la enseñanza de mecánica ventilatoria que integre un sistema de retroalimentación usando modelos de lenguaje
* Institución: Universidad del Valle
* Contacto: marcela.mazo@correounivalle.edu.co
*/

import { expect, test } from "@playwright/test";
import { freshGroup, releaseAttemptResults, retireEvaluation, runTag, type SeededEvaluation, seedEvaluation, signInTeacher } from "../support/evaluations";
import { contextFor } from "../support/learning";

test("(1) quiz: autosave, results held until the teacher release, AI feedback and its rating", async ({ browser, request, baseURL }) => {
  test.setTimeout(180_000);
  const teacher = await signInTeacher(request);
  const { groupId, students: [student] } = await freshGroup(request, teacher.api, "quiz");
  let evaluation: SeededEvaluation | null = null;

  try {
    evaluation = await seedEvaluation(teacher.api, {
      type: "QUIZ",
      title: `E2E quiz ${runTag()}`,
      questions: [
        { type: "SINGLE_CHOICE", prompt: "¿Qué parámetro se programa en VCV?", options: [{ content: "Volumen corriente", isCorrect: true }, { content: "Presión inspiratoria" }], explanation: "En VCV se fija el volumen." },
        { type: "SINGLE_CHOICE", prompt: "¿Qué valor de PEEP es fisiológico?", options: [{ content: "5 cmH2O", isCorrect: true }, { content: "20 cmH2O" }] },
      ],
    }, groupId);

    const context = await contextFor(browser, baseURL ?? "http://localhost:3000", student!);
    const page = await context.newPage();

    await page.goto(`/evaluations/${evaluation.id}`);
    await expect(page.getByRole("heading", { level: 1, name: evaluation.title })).toBeVisible({ timeout: 30_000 });
    await page.getByRole("button", { name: "Comenzar" }).click();
    await expect(page).toHaveURL(/\/attempts\/[^/]+$/, { timeout: 30_000 });
    const attemptId = new URL(page.url()).pathname.split("/").pop() ?? "";
    const isAnswerSave = (url: string, method: string) => method === "PUT" && /\/answers\/[^/]+$/.test(url);

    // No immediate feedback: every answer is just autosaved and stays editable.
    const firstSave = page.waitForResponse((res) => isAnswerSave(res.url(), res.request().method()) && res.ok());

    await page.getByRole("radio", { name: "Volumen corriente" }).check();
    await firstSave;
    const secondSave = page.waitForResponse((res) => isAnswerSave(res.url(), res.request().method()) && res.ok());

    await page.getByRole("radio", { name: "20 cmH2O" }).check();
    await secondSave;
    await expect(page.getByText("Respuesta guardada").first()).toBeVisible();
    await expect(page.getByText(/¡Correcto!|Casi\.|respuesta correcta/)).toHaveCount(0);
    await expect(page.getByText("En VCV se fija el volumen.")).toHaveCount(0);
    await expect(page.getByRole("radio", { name: "5 cmH2O" })).toBeEnabled();

    await page.getByRole("button", { name: "Enviar quiz" }).click();
    await page.getByRole("dialog", { name: "¿Enviar el intento?" }).getByRole("button", { name: "Enviar", exact: true }).click();
    await expect(page).toHaveURL(/\/result$/, { timeout: 30_000 });

    // Nothing is released yet: no grade, no count and no AI feedback.
    await expect(page.getByText("Entregado — en espera de resultados")).toBeVisible({ timeout: 30_000 });
    await expect(page.getByText(/correctas/)).toHaveCount(0);
    await expect(page.getByTestId("attempt-grade")).toHaveCount(0);
    await expect(page.getByRole("region", { name: "Retroalimentación general" })).toHaveCount(0);

    // The teacher releases the grade with the answers and the AI feedback.
    await releaseAttemptResults(teacher.api, attemptId, "GRADE_AND_ANSWERS");
    await page.reload();
    await expect(page.getByText("1 de 2 correctas")).toBeVisible({ timeout: 30_000 });
    await expect(page.getByText(/^(¡Aprobado! 🎉|Reprobado 😔)$/)).toBeVisible();
    await expect(page.getByText("En VCV se fija el volumen.")).toBeVisible();

    // General AI feedback from the fake LLM (not the deterministic fallback).
    const overall = page.getByRole("region", { name: "Retroalimentación general" });

    await expect(overall).toContainText("proveedor falso de E2E", { timeout: 60_000 });
    await expect(overall).not.toContainText("Retroalimentación automática");

    const rating = page.waitForRequest((req) => req.method() === "PUT" && req.url().endsWith("/api/ai-ratings"));
    const ratingResponse = page.waitForResponse((res) => res.request().method() === "PUT" && res.url().endsWith("/api/ai-ratings"));

    await expect(overall.getByText("¿Te fue útil?")).toBeVisible();
    await overall.getByRole("button", { name: "Sí, fue útil" }).click();
    expect((await rating).postDataJSON()).toMatchObject({ targetType: "GRADE_FEEDBACK", helpful: true, surface: "EVALUATION_FEEDBACK" });
    expect((await ratingResponse).ok()).toBe(true);
    await expect(overall.getByRole("button", { name: "Sí, fue útil" })).toHaveAttribute("aria-pressed", "true");

    // The rating survives a reload (embedded myRating).
    await page.reload();
    await expect(page.getByRole("region", { name: "Retroalimentación general" }).getByRole("button", { name: "Sí, fue útil" })).toHaveAttribute("aria-pressed", "true", { timeout: 30_000 });
    await context.close();
  } finally {
    await retireEvaluation(teacher.api, evaluation);
  }
});
