export type MessageRole = "user" | "assistant";

export type AiSourceCitation = {
  title: string
  url?: string | undefined
};

// Minimum payload of an AI stream `done` frame; each route may add fields (e.g. conversationId).
export type StreamDoneMetadata = {
  aiCallId: string
  messageId: string
  sources?: readonly AiSourceCitation[] | undefined
};

// Origin of an AI answer in the backend contract: DETERMINISTIC is a rule-based answer sent when no provider answered.
export type AnswerSource = "LLM" | "DETERMINISTIC";

// A missing or unknown source (older server) is treated as an LLM answer.
export function isFallbackSource(source: unknown): boolean {
  return source === "DETERMINISTIC";
}

// Label the backend puts at the start of a non-AI tutor answer (ventylab-server tutor-fallback.ts, es and en).
export const FALLBACK_ANSWER_LABELS: readonly string[] = ["[Respuesta automática sin IA]", "[Automatic answer, not generated by AI]"];

export function hasFallbackLabel(text: string): boolean {
  const trimmed = text.trimStart();

  return FALLBACK_ANSWER_LABELS.some((label) => trimmed.startsWith(label));
}

// Text without the leading fallback label (and the whitespace after it); other texts are returned unchanged.
export function stripFallbackLabel(text: string): string {
  const trimmed = text.trimStart();
  const label = FALLBACK_ANSWER_LABELS.find((candidate) => trimmed.startsWith(candidate));

  return label === undefined ? text : trimmed.slice(label.length).trimStart();
}

// Share of maxLength from which the composer shows its character counter.
export const COMPOSER_COUNTER_THRESHOLD = 0.9;

export function isNearLimit(length: number, maxLength: number): boolean {
  return maxLength > 0 && length >= Math.ceil(maxLength * COMPOSER_COUNTER_THRESHOLD);
}

export function isSafeExternalUrl(url: string | undefined): url is string {
  if (typeof url !== "string") {
    return false;
  }

  try {
    const { protocol } = new URL(url);

    return protocol === "https:" || protocol === "http:";
  } catch {
    return false;
  }
}
