import { describe, expect, it } from "vitest";
import { hasFallbackLabel, isFallbackSource, stripFallbackLabel } from "./ai-conversation.entity";

describe("isFallbackSource", () => {
  it("is true only for DETERMINISTIC", () => {
    expect(isFallbackSource("DETERMINISTIC")).toBe(true);
    expect(isFallbackSource("LLM")).toBe(false);
    expect(isFallbackSource(undefined)).toBe(false);
    expect(isFallbackSource("deterministic")).toBe(false);
  });
});

describe("fallback label", () => {
  it("detects the Spanish and English server labels at the start of the text", () => {
    expect(hasFallbackLabel("[Respuesta automática sin IA] Revisa la lección.")).toBe(true);
    expect(hasFallbackLabel("\n [Automatic answer, not generated by AI] Review the lesson.")).toBe(true);
    expect(hasFallbackLabel("La PEEP [Respuesta automática sin IA]")).toBe(false);
  });

  it("strips the label and the whitespace after it, and leaves other texts unchanged", () => {
    expect(stripFallbackLabel("[Respuesta automática sin IA]\n\nRevisa la lección.")).toBe("Revisa la lección.");
    expect(stripFallbackLabel("[Automatic answer, not generated by AI] Review it.")).toBe("Review it.");
    expect(stripFallbackLabel("  La PEEP es…")).toBe("  La PEEP es…");
  });
});
